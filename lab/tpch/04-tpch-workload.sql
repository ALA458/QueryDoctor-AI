;WITH DE_SUPP AS (
    SELECT -- QD-TPCH:Q11:
        S.S_SUPPKEY
    FROM dbo.SUPPLIER S
    JOIN dbo.NATION N ON S.S_NATIONKEY = N.N_NATIONKEY
    WHERE N.N_NAME = 'GERMANY'
),
PART_VALUES AS (
    SELECT
        PS.PS_PARTKEY,
        SUM(PS.PS_SUPPLYCOST * PS.PS_AVAILQTY) AS VALUE_TOTAL
    FROM dbo.PARTSUPP PS
    JOIN DE_SUPP DS ON PS.PS_SUPPKEY = DS.S_SUPPKEY
    GROUP BY PS.PS_PARTKEY
)
SELECT
    PV.PS_PARTKEY,
    PV.VALUE_TOTAL
FROM PART_VALUES PV
WHERE PV.VALUE_TOTAL > (
    SELECT SUM(PV2.VALUE_TOTAL) * 0.001
    FROM PART_VALUES PV2
)
ORDER BY PV.VALUE_TOTAL DESC;
GO

SELECT -- QD-TPCH:Q12:
    L.L_SHIPMODE,
    SUM(CASE WHEN O.O_ORDERPRIORITY = '1-URGENT' OR O.O_ORDERPRIORITY = '2-HIGH' THEN 1 ELSE 0 END) AS HIGH_LINE_COUNT,
    SUM(CASE WHEN O.O_ORDERPRIORITY <> '1-URGENT' AND O.O_ORDERPRIORITY <> '2-HIGH' THEN 1 ELSE 0 END) AS LOW_LINE_COUNT
FROM dbo.ORDERS O
JOIN dbo.LINEITEM L ON O.O_ORDERKEY = L.L_ORDERKEY
WHERE L.L_SHIPMODE IN ('MAIL', 'SHIP')
  AND L.L_COMMITDATE < L.L_RECEIPTDATE
  AND L.L_SHIPDATE < L.L_COMMITDATE
  AND L.L_RECEIPTDATE >= DATEFROMPARTS(1994, 1, 1)
  AND L.L_RECEIPTDATE < DATEADD(YEAR, 1, DATEFROMPARTS(1994, 1, 1))
GROUP BY L.L_SHIPMODE
ORDER BY L.L_SHIPMODE ASC;
GO

SELECT -- QD-TPCH:Q13:
    C_COUNT,
    COUNT(*) AS CUSTDIST
FROM (
    SELECT
        C.C_CUSTKEY,
        COUNT(O.O_ORDERKEY) AS C_COUNT
    FROM dbo.CUSTOMER C
    LEFT OUTER JOIN dbo.ORDERS O
      ON C.C_CUSTKEY = O.O_CUSTKEY
     AND O.O_COMMENT NOT LIKE '%special%requests%'
    GROUP BY C.C_CUSTKEY
) AS C_ORDERS
GROUP BY C_COUNT
ORDER BY CUSTDIST DESC, C_COUNT DESC;
GO

SELECT -- QD-TPCH:Q14:
    100.00 * SUM(CASE WHEN P.P_TYPE LIKE 'PROMO%' THEN L.L_EXTENDEDPRICE * (1 - L.L_DISCOUNT) ELSE 0 END)
    / NULLIF(SUM(L.L_EXTENDEDPRICE * (1 - L.L_DISCOUNT)), 0) AS PROMO_REVENUE
FROM dbo.LINEITEM L
JOIN dbo.PART P ON L.L_PARTKEY = P.P_PARTKEY
WHERE L.L_SHIPDATE >= CAST('1995-09-01' AS date)
  AND L.L_SHIPDATE < DATEADD(MONTH, 1, CAST('1995-09-01' AS date));
GO

;WITH REVENUE0 AS (
    SELECT -- QD-TPCH:Q15:
        L_SUPPKEY AS SUPPLIER_NO,
        SUM(L_EXTENDEDPRICE * (1 - L_DISCOUNT)) AS TOTAL_REVENUE
    FROM dbo.LINEITEM
    WHERE L_SHIPDATE >= CAST('1996-01-01' AS date)
      AND L_SHIPDATE < DATEADD(MONTH, 3, CAST('1996-01-01' AS date))
    GROUP BY L_SUPPKEY
)
