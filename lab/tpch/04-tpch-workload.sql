SELECT -- QD-TPCH:Q01:
    L_RETURNFLAG,
    L_LINESTATUS,
    SUM(L_QUANTITY) AS SUM_QTY,
    SUM(L_EXTENDEDPRICE) AS SUM_BASE_PRICE,
    SUM(L_EXTENDEDPRICE * (1 - L_DISCOUNT)) AS SUM_DISC_PRICE,
    SUM(L_EXTENDEDPRICE * (1 - L_DISCOUNT) * (1 + L_TAX)) AS SUM_CHARGE,
    AVG(L_QUANTITY) AS AVG_QTY,
    AVG(L_EXTENDEDPRICE) AS AVG_PRICE,
    AVG(L_DISCOUNT) AS AVG_DISC,
    COUNT(*) AS COUNT_ORDER
FROM dbo.LINEITEM
WHERE L_SHIPDATE <= DATEADD(DAY, -90, CAST('1998-12-01' AS date))
GROUP BY L_RETURNFLAG, L_LINESTATUS
ORDER BY L_RETURNFLAG ASC, L_LINESTATUS ASC;
GO

SELECT TOP (100) -- QD-TPCH:Q02:
    S.S_ACCTBAL,
    S.S_NAME,
    N.N_NAME,
    P.P_PARTKEY,
    P.P_MFGR,
    S.S_ADDRESS,
    S.S_PHONE,
    S.S_COMMENT
FROM dbo.PART P
JOIN dbo.PARTSUPP PS ON P.P_PARTKEY = PS.PS_PARTKEY
JOIN dbo.SUPPLIER S ON S.S_SUPPKEY = PS.PS_SUPPKEY
JOIN dbo.NATION N ON S.S_NATIONKEY = N.N_NATIONKEY
JOIN dbo.REGION R ON N.N_REGIONKEY = R.R_REGIONKEY
WHERE P.P_SIZE = 15
  AND P.P_TYPE LIKE '%STEEL'
  AND R.R_NAME = 'EUROPE'
  AND PS.PS_SUPPLYCOST = (
      SELECT MIN(PS2.PS_SUPPLYCOST)
      FROM dbo.PARTSUPP PS2
      JOIN dbo.SUPPLIER S2 ON S2.S_SUPPKEY = PS2.PS_SUPPKEY
      JOIN dbo.NATION N2 ON S2.S_NATIONKEY = N2.N_NATIONKEY
      JOIN dbo.REGION R2 ON N2.N_REGIONKEY = R2.R_REGIONKEY
      WHERE P.P_PARTKEY = PS2.PS_PARTKEY
        AND R2.R_NAME = 'EUROPE'
  )
ORDER BY S.S_ACCTBAL DESC, N.N_NAME ASC, S.S_NAME ASC, P.P_PARTKEY ASC;
GO

SELECT TOP (10) -- QD-TPCH:Q03:
    L.L_ORDERKEY,
    SUM(L.L_EXTENDEDPRICE * (1 - L.L_DISCOUNT)) AS REVENUE,
    O.O_ORDERDATE,
    O.O_SHIPPRIORITY
FROM dbo.CUSTOMER C
JOIN dbo.ORDERS O ON C.C_CUSTKEY = O.O_CUSTKEY
JOIN dbo.LINEITEM L ON L.L_ORDERKEY = O.O_ORDERKEY
WHERE C.C_MKTSEGMENT = 'BUILDING'
  AND O.O_ORDERDATE < CAST('1995-03-15' AS date)
  AND L.L_SHIPDATE > CAST('1995-03-15' AS date)
GROUP BY L.L_ORDERKEY, O.O_ORDERDATE, O.O_SHIPPRIORITY
ORDER BY REVENUE DESC, O.O_ORDERDATE ASC;
GO

SELECT -- QD-TPCH:Q04:
    O.O_ORDERPRIORITY,
    COUNT(*) AS ORDER_COUNT
FROM dbo.ORDERS O
WHERE O.O_ORDERDATE >= CAST('1993-07-01' AS date)
  AND O.O_ORDERDATE < DATEADD(MONTH, 3, CAST('1993-07-01' AS date))
  AND O.O_ORDERKEY IN (
      SELECT L.L_ORDERKEY
      FROM dbo.LINEITEM L
      WHERE L.L_COMMITDATE < L.L_RECEIPTDATE
  )
GROUP BY O.O_ORDERPRIORITY
ORDER BY O.O_ORDERPRIORITY ASC;
GO

;WITH ASIA_SUPP AS (
    SELECT -- QD-TPCH:Q05:
        S.S_SUPPKEY,
        N.N_NATIONKEY,
        N.N_NAME
    FROM dbo.SUPPLIER S
    JOIN dbo.NATION N ON S.S_NATIONKEY = N.N_NATIONKEY
    JOIN dbo.REGION R ON N.N_REGIONKEY = R.R_REGIONKEY
    WHERE R.R_NAME = 'ASIA'
),
ASIA_CUST_ORDERS AS (
    SELECT
        O.O_ORDERKEY,
        A.N_NAME,
        A.S_SUPPKEY
    FROM dbo.CUSTOMER C
    JOIN dbo.ORDERS O ON C.C_CUSTKEY = O.O_CUSTKEY
    JOIN ASIA_SUPP A ON C.C_NATIONKEY = A.N_NATIONKEY
    WHERE O.O_ORDERDATE >= DATEFROMPARTS(1994, 1, 1)
      AND O.O_ORDERDATE < DATEADD(YEAR, 1, DATEFROMPARTS(1994, 1, 1))
)
SELECT
    ACO.N_NAME,
    SUM(L.L_EXTENDEDPRICE * (1 - L.L_DISCOUNT)) AS REVENUE
FROM ASIA_CUST_ORDERS ACO
JOIN dbo.LINEITEM L ON L.L_ORDERKEY = ACO.O_ORDERKEY AND L.L_SUPPKEY = ACO.S_SUPPKEY
GROUP BY ACO.N_NAME
ORDER BY REVENUE DESC;
GO

SELECT -- QD-TPCH:Q06:
    SUM(L_EXTENDEDPRICE * L_DISCOUNT) AS REVENUE
FROM dbo.LINEITEM
WHERE L_SHIPDATE >= DATEFROMPARTS(1994, 1, 1)
  AND L_SHIPDATE < DATEADD(YEAR, 1, DATEFROMPARTS(1994, 1, 1))
  AND L_DISCOUNT BETWEEN 0.05 AND 0.07
  AND L_QUANTITY < 24;
GO

;WITH TARGET_NATIONS AS (
    SELECT -- QD-TPCH:Q07:
        N_NATIONKEY,
        N_NAME
    FROM dbo.NATION
    WHERE N_NAME IN ('FRANCE', 'GERMANY')
)
SELECT
    SUPP_NATION,
    CUST_NATION,
    L_YEAR,
    SUM(VOLUME) AS REVENUE
FROM (
    SELECT
        N1.N_NAME AS SUPP_NATION,
        N2.N_NAME AS CUST_NATION,
        YEAR(L.L_SHIPDATE) AS L_YEAR,
        L.L_EXTENDEDPRICE * (1 - L.L_DISCOUNT) AS VOLUME
    FROM dbo.SUPPLIER S
    JOIN dbo.LINEITEM L ON S.S_SUPPKEY = L.L_SUPPKEY
    JOIN dbo.ORDERS O ON O.O_ORDERKEY = L.L_ORDERKEY
    JOIN dbo.CUSTOMER C ON C.C_CUSTKEY = O.O_CUSTKEY
    JOIN TARGET_NATIONS N1 ON S.S_NATIONKEY = N1.N_NATIONKEY
    JOIN TARGET_NATIONS N2 ON C.C_NATIONKEY = N2.N_NATIONKEY
    WHERE N1.N_NATIONKEY <> N2.N_NATIONKEY
      AND L.L_SHIPDATE BETWEEN CAST('1995-01-01' AS date) AND CAST('1996-12-31' AS date)
) AS SHIPPING
GROUP BY SUPP_NATION, CUST_NATION, L_YEAR
ORDER BY SUPP_NATION ASC, CUST_NATION ASC, L_YEAR ASC;
GO

SELECT -- QD-TPCH:Q08:
    O_YEAR,
    SUM(CASE WHEN NATION = 'BRAZIL' THEN VOLUME ELSE 0 END) / NULLIF(SUM(VOLUME), 0) AS MKT_SHARE
FROM (
    SELECT
        YEAR(O.O_ORDERDATE) AS O_YEAR,
        L.L_EXTENDEDPRICE * (1 - L.L_DISCOUNT) AS VOLUME,
        N2.N_NAME AS NATION
    FROM dbo.PART P
    JOIN dbo.LINEITEM L ON P.P_PARTKEY = L.L_PARTKEY
    JOIN dbo.SUPPLIER S ON S.S_SUPPKEY = L.L_SUPPKEY
    JOIN dbo.ORDERS O ON L.L_ORDERKEY = O.O_ORDERKEY
    JOIN dbo.CUSTOMER C ON O.O_CUSTKEY = C.C_CUSTKEY
    JOIN dbo.NATION N1 ON C.C_NATIONKEY = N1.N_NATIONKEY
    JOIN dbo.REGION R ON N1.N_REGIONKEY = R.R_REGIONKEY
    JOIN dbo.NATION N2 ON S.S_NATIONKEY = N2.N_NATIONKEY
    WHERE R.R_NAME = 'AMERICA'
      AND O.O_ORDERDATE BETWEEN CAST('1995-01-01' AS date) AND CAST('1996-12-31' AS date)
      AND P.P_TYPE = 'ECONOMY ANODIZED BRASS'
) AS ALL_NATIONS
GROUP BY O_YEAR
ORDER BY O_YEAR ASC;
GO

SELECT -- QD-TPCH:Q09:
    NATION,
    O_YEAR,
    SUM(AMOUNT) AS SUM_PROFIT
FROM (
    SELECT
        N.N_NAME AS NATION,
        YEAR(O.O_ORDERDATE) AS O_YEAR,
        L.L_EXTENDEDPRICE * (1 - L.L_DISCOUNT) - PS.PS_SUPPLYCOST * L.L_QUANTITY AS AMOUNT
    FROM dbo.PART P
    JOIN dbo.LINEITEM L ON P.P_PARTKEY = L.L_PARTKEY
    JOIN dbo.SUPPLIER S ON S.S_SUPPKEY = L.L_SUPPKEY
    JOIN dbo.PARTSUPP PS ON PS.PS_SUPPKEY = L.L_SUPPKEY AND PS.PS_PARTKEY = L.L_PARTKEY
    JOIN dbo.ORDERS O ON O.O_ORDERKEY = L.L_ORDERKEY
    JOIN dbo.NATION N ON S.S_NATIONKEY = N.N_NATIONKEY
    WHERE P.P_NAME LIKE '%green%'
) AS PROFIT
GROUP BY NATION, O_YEAR
ORDER BY NATION ASC, O_YEAR DESC;
GO

SELECT TOP (20) -- QD-TPCH:Q10:
