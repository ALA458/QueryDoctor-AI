SELECT -- QD-TPCH:Q17:
    SUM(L.L_EXTENDEDPRICE) / 7.0 AS AVG_YEARLY
FROM dbo.LINEITEM L
JOIN dbo.PART P ON P.P_PARTKEY = L.L_PARTKEY
WHERE P.P_BRAND = 'Brand#23'
  AND P.P_CONTAINER = 'MED BOX'
  AND L.L_QUANTITY < (
      SELECT 0.2 * AVG(L2.L_QUANTITY)
      FROM dbo.LINEITEM L2
      WHERE L2.L_PARTKEY = P.P_PARTKEY
  );
GO

SELECT TOP (100) -- QD-TPCH:Q18:
    C.C_NAME,
    C.C_CUSTKEY,
    O.O_ORDERKEY,
    O.O_ORDERDATE,
    O.O_TOTALPRICE,
    SUM(L.L_QUANTITY) AS TOTAL_QTY
FROM dbo.CUSTOMER C
JOIN dbo.ORDERS O ON C.C_CUSTKEY = O.O_CUSTKEY
JOIN dbo.LINEITEM L ON O.O_ORDERKEY = L.L_ORDERKEY
WHERE O.O_ORDERKEY IN (
    SELECT L2.L_ORDERKEY
    FROM dbo.LINEITEM L2
    GROUP BY L2.L_ORDERKEY
    HAVING SUM(L2.L_QUANTITY) > 150
)
GROUP BY C.C_NAME, C.C_CUSTKEY, O.O_ORDERKEY, O.O_ORDERDATE, O.O_TOTALPRICE
ORDER BY O.O_TOTALPRICE DESC, O.O_ORDERDATE ASC;
GO

SELECT -- QD-TPCH:Q19:
    SUM(L.L_EXTENDEDPRICE * (1 - L.L_DISCOUNT)) AS REVENUE
FROM dbo.LINEITEM L
JOIN dbo.PART P ON P.P_PARTKEY = L.L_PARTKEY
WHERE L.L_SHIPMODE IN ('AIR', 'AIR REG')
  AND L.L_SHIPINSTRUCT = 'DELIVER IN PERSON'
  AND (
      (
          P.P_BRAND = 'Brand#12'
          AND P.P_CONTAINER IN ('SM CASE', 'SM BOX', 'SM PACK', 'SM PKG')
          AND L.L_QUANTITY >= 1 AND L.L_QUANTITY <= 11
          AND P.P_SIZE BETWEEN 1 AND 5
      ) OR (
          P.P_BRAND = 'Brand#23'
          AND P.P_CONTAINER IN ('MED BAG', 'MED BOX', 'MED PKG', 'MED PACK')
          AND L.L_QUANTITY >= 10 AND L.L_QUANTITY <= 20
          AND P.P_SIZE BETWEEN 1 AND 10
      ) OR (
          P.P_BRAND = 'Brand#34'
          AND P.P_CONTAINER IN ('LG CASE', 'LG BOX', 'LG PACK', 'LG PKG')
          AND L.L_QUANTITY >= 20 AND L.L_QUANTITY <= 30
          AND P.P_SIZE BETWEEN 1 AND 15
      )
  );
GO

SELECT -- QD-TPCH:Q20:
    S.S_NAME,
    S.S_ADDRESS
FROM dbo.SUPPLIER S
JOIN dbo.NATION N ON S.S_NATIONKEY = N.N_NATIONKEY
WHERE S.S_SUPPKEY IN (
    SELECT PS.PS_SUPPKEY
    FROM dbo.PARTSUPP PS
    WHERE PS.PS_PARTKEY IN (
        SELECT P.P_PARTKEY
        FROM dbo.PART P
        WHERE P.P_NAME LIKE 'part green%'
    )
      AND PS.PS_AVAILQTY > (
          SELECT 0.5 * SUM(L.L_QUANTITY)
          FROM dbo.LINEITEM L
          WHERE L.L_PARTKEY = PS.PS_PARTKEY
            AND L.L_SUPPKEY = PS.PS_SUPPKEY
            AND L.L_SHIPDATE >= DATEFROMPARTS(1994, 1, 1)
            AND L.L_SHIPDATE < DATEADD(YEAR, 1, DATEFROMPARTS(1994, 1, 1))
      )
)
  AND N.N_NAME = 'CANADA'
ORDER BY S.S_NAME ASC;
GO

SELECT TOP (100) -- QD-TPCH:Q21:
    S.S_NAME,
    COUNT(*) AS NUMWAIT
FROM dbo.SUPPLIER S
JOIN dbo.LINEITEM L1 ON S.S_SUPPKEY = L1.L_SUPPKEY
JOIN dbo.ORDERS O ON O.O_ORDERKEY = L1.L_ORDERKEY
JOIN dbo.NATION N ON S.S_NATIONKEY = N.N_NATIONKEY
WHERE O.O_ORDERSTATUS = 'F'
  AND L1.L_RECEIPTDATE > L1.L_COMMITDATE
  AND EXISTS (
      SELECT 1
      FROM dbo.LINEITEM L2
      WHERE L2.L_ORDERKEY = L1.L_ORDERKEY
        AND L2.L_SUPPKEY <> L1.L_SUPPKEY
  )
  AND NOT EXISTS (
      SELECT 1
      FROM dbo.LINEITEM L3
      WHERE L3.L_ORDERKEY = L1.L_ORDERKEY
        AND L3.L_SUPPKEY <> L1.L_SUPPKEY
        AND L3.L_RECEIPTDATE > L3.L_COMMITDATE
  )
  AND N.N_NAME = 'SAUDI ARABIA'
GROUP BY S.S_NAME
ORDER BY NUMWAIT DESC, S.S_NAME ASC;
GO

SELECT -- QD-TPCH:Q22:
    CNTRYCODE,
    COUNT(*) AS NUMCUST,
    SUM(C_ACCTBAL) AS TOTACCTBAL
FROM (
    SELECT
        SUBSTRING(C.C_PHONE, 1, 2) AS CNTRYCODE,
        C.C_ACCTBAL
    FROM dbo.CUSTOMER C
    WHERE SUBSTRING(C.C_PHONE, 1, 2) IN ('13', '31', '23', '29', '30', '18', '17')
      AND C.C_ACCTBAL > (
          SELECT AVG(C2.C_ACCTBAL)
          FROM dbo.CUSTOMER C2
          WHERE C2.C_ACCTBAL > 0.00
            AND SUBSTRING(C2.C_PHONE, 1, 2) IN ('13', '31', '23', '29', '30', '18', '17')
      )
      AND NOT EXISTS (
          SELECT 1
          FROM dbo.ORDERS O
          WHERE O.O_CUSTKEY = C.C_CUSTKEY
      )
) AS CUSTSALE
GROUP BY CNTRYCODE
ORDER BY CNTRYCODE ASC;
GO

