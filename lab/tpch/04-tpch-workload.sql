SELECT -- QD-TPCH:Q16:
    P.P_BRAND,
    P.P_TYPE,
    P.P_SIZE,
    COUNT(DISTINCT PS.PS_SUPPKEY) AS SUPPLIER_CNT
FROM dbo.PARTSUPP PS
JOIN dbo.PART P ON P.P_PARTKEY = PS.PS_PARTKEY
WHERE P.P_BRAND <> 'Brand#45'
  AND P.P_TYPE NOT LIKE 'MEDIUM POLISHED%'
  AND P.P_SIZE IN (49, 14, 23, 45, 19, 3, 36, 9)
  AND PS.PS_SUPPKEY NOT IN (
      SELECT S.S_SUPPKEY
      FROM dbo.SUPPLIER S
      WHERE CHARINDEX('Customer', S.S_COMMENT) > 0
        AND CHARINDEX('Complaints', S.S_COMMENT, CHARINDEX('Customer', S.S_COMMENT) + 8) > 0
  )
GROUP BY P.P_BRAND, P.P_TYPE, P.P_SIZE
ORDER BY SUPPLIER_CNT DESC, P.P_BRAND ASC, P.P_TYPE ASC, P.P_SIZE ASC;
